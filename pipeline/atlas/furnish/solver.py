"""Place furniture in rooms under real spatial constraints.

The naive approach — drop the bed at the room centroid, rotate to taste — produces
layouts that are instantly wrong: beds blocking doors, wardrobes that cannot open,
sofas floating in the middle of the floor. Furniture placement is a constraint
problem, and the constraints are the ones a designer works to:

* **Large items back onto a wall.** People do not put a wardrobe in the middle of
  a room. Candidate positions are generated by sliding each item along each wall
  segment, which is both a small search space and exactly where the answers are.

* **Clearance is required, not preferred.** A wardrobe with 300 mm in front of it
  is unusable. Each item declares the free space it needs and a candidate that
  violates it is rejected outright rather than penalised.

* **Doors must stay usable.** A door swing is a quarter-disc of floor that has to
  stay clear. This is the constraint most often missed, and its absence is
  immediately obvious in a walkthrough.

* **The drawing wins.** Sanitaryware and kitchen counters read from the CAD file
  are locked: they encode plumbing stacks and service runs that cannot be moved by
  a layout heuristic. The solver places around them.

Candidates that satisfy every hard constraint are then *scored*, and the scoring is
where design judgement lives: prefer the longest uninterrupted wall for a bed,
prefer facing the window from a sofa, prefer symmetry, keep circulation clear.

Deterministic by construction — no randomness — so the same plan always produces
the same layout and a designer's edits are not undone by a rerun.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field, replace
from typing import Sequence

from shapely.geometry import LineString, MultiPolygon, Point as ShpPoint, Polygon as ShpPolygon, box as shp_box
from shapely.ops import unary_union

from ..planir import Opening, OpeningKind, PlanIR, Room, RoomKind, Source, Wall
from ..sceneir import MM_TO_M, FurniturePlacement
from .catalog import CATALOG, Anchor, FurnitureItem, items_for_room

__all__ = ["SolverConfig", "LayoutResult", "furnish_room", "furnish_plan"]


@dataclass(slots=True)
class SolverConfig:
    wall_gap_mm: float = 20.0
    """Small air gap between furniture and wall, so faces do not z-fight."""

    slide_step_mm: float = 100.0
    """Granularity of candidate positions along a wall. 100 mm is finer than a
    viewer can perceive and keeps the search cheap."""

    circulation_width_mm: float = 750.0
    """Minimum walkable corridor to preserve through a room."""

    door_swing_margin_mm: float = 60.0
    max_items_per_room: int = 9
    respect_locked: bool = True
    """Honour fixtures read from the drawing instead of re-planning them."""

    wall_host_tol_m: float = 0.75
    """How close a wall must run to a room's boundary to host furniture in it."""

    min_wall_length_mm: float = 600.0
    """Ignore wall stubs shorter than this as anchor candidates."""


@dataclass
class LayoutResult:
    placements: list[FurniturePlacement] = field(default_factory=list)
    rejected: dict[str, str] = field(default_factory=dict)
    """Item id -> why it did not fit. Surfaced in the UI so "why is there no
    wardrobe in the guest bedroom" has an answer rather than a shrug."""

    notes: list[str] = field(default_factory=list)


@dataclass(slots=True)
class _Candidate:
    x: float
    z: float
    """Position in scene metres."""

    yaw: float
    score: float
    wall_id: str | None
    reason: str


def _shrink_steps(min_scale: float) -> list[float]:
    """Sizes to try, largest first, down to ``min_scale``.

    Coarse and few: these stand for the sizes a manufacturer actually offers, so trying
    every percent would be both slower and dishonest about what it means.
    """
    if min_scale >= 0.999:
        return [1.0]
    steps = [1.0, 0.9, 0.8, 0.7, 0.65]
    return [f for f in steps if f >= min_scale - 1e-6] or [min_scale]


def _scaled(item: FurnitureItem, factor: float) -> FurnitureItem:
    """A copy of ``item`` at ``factor`` of its size.

    Footprint and clearances scale; **height does not**. A shorter desk is not a desk — work
    surfaces, seat heights and counter heights are set by the human body, not by how much
    floor is spare. Clearances scale because they are proportional to the item's use: a
    narrower desk needs less room to pull a chair out.
    """
    if factor >= 0.999:
        return item
    return replace(
        item,
        width_mm=item.width_mm * factor,
        depth_mm=item.depth_mm * factor,
        clearance_front_mm=item.clearance_front_mm * factor,
        clearance_back_mm=item.clearance_back_mm * factor,
        clearance_sides_mm=item.clearance_sides_mm * factor,
    )


def _room_polygon_m(room: Room, origin: tuple[float, float]) -> ShpPolygon:
    ox, oy = origin
    poly = ShpPolygon([((x - ox) * MM_TO_M, -(y - oy) * MM_TO_M) for x, y in room.polygon])
    if not poly.is_valid:
        # A ring that touches itself at a point (a healed floor's pinch) is invalid to
        # shapely and every boolean op on it raises TopologyException mid-furnish.
        fixed = poly.buffer(0)
        if isinstance(fixed, MultiPolygon) and not fixed.is_empty:
            fixed = max(fixed.geoms, key=lambda g: g.area)
        if isinstance(fixed, ShpPolygon) and not fixed.is_empty:
            return fixed
    return poly


def _wall_line_m(wall: Wall, origin: tuple[float, float]) -> LineString:
    ox, oy = origin
    return LineString(
        [
            ((wall.start[0] - ox) * MM_TO_M, -(wall.start[1] - oy) * MM_TO_M),
            ((wall.end[0] - ox) * MM_TO_M, -(wall.end[1] - oy) * MM_TO_M),
        ]
    )


def _dominant_axis(coords: Sequence[tuple[float, float]]) -> float:
    """Yaw of the room's longest edge direction, folded into [0, pi/2).

    Rooms are overwhelmingly rectilinear, so one edge direction plus its quarter turns
    describes every wall. Corner-placed items snap to it instead of inventing an angle.
    """
    best_len, best = 0.0, 0.0
    n = len(coords)
    for i in range(n):
        ax, az = coords[i]
        bx, bz = coords[(i + 1) % n]
        L = math.hypot(bx - ax, bz - az)
        if L > best_len:
            best_len, best = L, math.atan2(bx - ax, bz - az)
    return best % (math.pi / 2)


def _oriented_box(cx: float, cz: float, w: float, d: float, yaw: float) -> ShpPolygon:
    """Footprint rectangle centred at ``(cx, cz)``, rotated by ``yaw`` about Y."""
    hw, hd = w / 2.0, d / 2.0
    cos_y, sin_y = math.cos(yaw), math.sin(yaw)
    pts = []
    for lx, lz in ((-hw, -hd), (hw, -hd), (hw, hd), (-hw, hd)):
        pts.append((cx + lx * cos_y + lz * sin_y, cz - lx * sin_y + lz * cos_y))
    return ShpPolygon(pts)


def _line_direction(line: LineString) -> tuple[float, float]:
    """Unit vector along a two-point line."""
    (x0, y0), (x1, y1) = line.coords[0], line.coords[-1]
    dx, dy = x1 - x0, y1 - y0
    n = math.hypot(dx, dy) or 1.0
    return (dx / n, dy / n)


def _door_swing_zones(
    plan: PlanIR, room: Room, origin: tuple[float, float], cfg: SolverConfig
) -> tuple[list[ShpPolygon], list[ShpPolygon]]:
    """Floor a door needs in order to open, as polygons in scene metres.

    A hinged leaf sweeps a **quarter-disc**: radius of one leaf width, centred on the
    hinge jamb, spanning ninety degrees from the wall plane into the room it opens into.

    It was previously a *full disc* of that radius centred on the middle of the opening,
    which is a much bigger claim — 2.5 m² for an ordinary 900 mm door, and it reached
    behind the hinge and through the wall into the next room. Worse, it was applied to
    sliding doors too, and a sliding door does not sweep anything: the 3.35 m balcony
    threshold generated a 36 m² disc that swallowed an 8.7 m² balcony whole, so every
    piece of balcony furniture was rejected as blocking a door. Fourteen of thirty
    placement failures were that one mistake.
    """
    hard: list[ShpPolygon] = []
    soft: list[ShpPolygon] = []
    poly = _room_polygon_m(room, origin)
    for o in plan.openings:
        if not o.kind.is_door:
            continue
        wall = plan.wall_by_id(o.wall_id)
        if wall is None:
            continue
        line = _wall_line_m(wall, origin)
        centre = line.interpolate(o.t_center, normalized=True)
        if poly.distance(centre) > 0.5:
            continue

        width = o.width_mm * MM_TO_M
        margin = cfg.door_swing_margin_mm * MM_TO_M
        along = _line_direction(line)
        normal = (-along[1], along[0])
        # Which side is the room on? Probe both ways.
        probe = 0.35
        if not poly.contains(ShpPoint(centre.x + normal[0] * probe, centre.y + normal[1] * probe)):
            normal = (-normal[0], -normal[1])

        if o.kind is OpeningKind.SLIDING_DOOR:
            # Slides in the wall plane, so it needs a threshold kept clear to walk
            # through — not a swept arc, and **not the full width of the opening**.
            #
            # A sliding door opens half its width: the other half is where the panel parks,
            # which is exactly how the leaf is modelled in both renderers. Claiming the
            # whole width took 2 m² of clear floor out of a 4 m² balcony for a 3.35 m patio
            # door, so every balcony chair was rejected for blocking a door it does not
            # reach. Half the width, on the side that opens.
            depth = max(0.6, margin)
            half = width / 2.0
            # The leaf parks over the negative-along half, so the passable half is positive.
            a0 = 0.0
            a1 = half
            zone = ShpPolygon(
                [
                    (centre.x + along[0] * a0, centre.y + along[1] * a0),
                    (centre.x + along[0] * a1, centre.y + along[1] * a1),
                    (
                        centre.x + along[0] * a1 + normal[0] * depth,
                        centre.y + along[1] * a1 + normal[1] * depth,
                    ),
                    (
                        centre.x + along[0] * a0 + normal[0] * depth,
                        centre.y + along[1] * a0 + normal[1] * depth,
                    ),
                ]
            )
        else:
            r = width + margin
            side = -1.0 if o.swing == "right" else 1.0
            hinge = (centre.x + along[0] * side * width / 2, centre.y + along[1] * side * width / 2)
            a0 = math.atan2(-along[1] * side, -along[0] * side)
            a1 = math.atan2(normal[1], normal[0])
            # Shortest way round from the wall plane to the room-side normal: 90 degrees.
            sweep = (a1 - a0 + math.pi) % (2 * math.pi) - math.pi
            steps = 8
            pts = [hinge] + [
                (hinge[0] + r * math.cos(a0 + sweep * k / steps), hinge[1] + r * math.sin(a0 + sweep * k / steps))
                for k in range(steps + 1)
            ]
            zone = ShpPolygon(pts)
        if not zone.is_valid:
            zone = zone.buffer(0)
        zone = zone.intersection(poly) if not zone.is_empty else zone
        if zone.is_empty:
            continue
        # A door read from the drawing is a fact and its swing is inviolable. A door
        # *inferred* because the room would otherwise be unreachable is a guess about
        # position, so letting it hard-veto furniture would have a guess evict a real
        # sofa. It becomes a strong preference instead.
        (soft if o.source is Source.INFERRED else hard).append(zone)
    return hard, soft


def _anchor_candidates(
    item: FurnitureItem,
    room: Room,
    walls: Sequence[Wall],
    origin: tuple[float, float],
    cfg: SolverConfig,
) -> list[_Candidate]:
    """Generate candidate placements according to the item's anchor rule."""
    poly = _room_polygon_m(room, origin)
    cx, cz = poly.centroid.x, poly.centroid.y
    w = item.width_mm * MM_TO_M
    d = item.depth_mm * MM_TO_M
    gap = cfg.wall_gap_mm * MM_TO_M
    out: list[_Candidate] = []

    if item.anchor in (Anchor.CENTRE, Anchor.FREE):
        return _open_floor_candidates(poly, cfg)


    # Walls bounding this room: those running close to the room's boundary.
    #
    # The tolerance is generous on purpose. Where an open-plan region was split into
    # zones by label, a zone's boundary is a quantised line through the middle of the
    # room and lies nowhere near a wall — only the zone's *outer* edges do. A tight
    # tolerance found no host wall at all for those zones, so the living room came out
    # with no sofa and no coffee table. Widening it recovers the real walls without
    # inventing any: the containment probe below still rejects a wall whose other side
    # is a different room.
    boundary = poly.exterior
    hosts: list[tuple[Wall, LineString]] = []
    for wall in walls:
        if wall.length_mm < cfg.min_wall_length_mm:
            continue
        line = _wall_line_m(wall, origin)
        if line.distance(boundary) < cfg.wall_host_tol_m:
            hosts.append((wall, line))

    if item.anchor is Anchor.CORNER:
        # A shower tray or a planter sits square in the corner, aligned to the two
        # walls that form it. Facing the room *centroid* instead gives an arbitrary
        # diagonal yaw — which is why showers were rendering rotated 30-40 degrees in
        # the middle of bathrooms, an error impossible to miss in plan and impossible
        # to see in a coordinate dump. Yaw is therefore snapped to the room's own wall
        # directions.
        coords = list(poly.exterior.coords[:-1])
        axis = _dominant_axis(coords)
        for px, pz in coords:
            vx, vz = cx - px, cz - pz
            n = math.hypot(vx, vz)
            if n < 1e-6:
                continue
            inset = math.hypot(w, d) / 2.0 + gap
            ix, iz = px + vx / n * inset, pz + vz / n * inset
            if not poly.contains(ShpPoint(ix, iz)):
                continue
            # Face the room along whichever wall direction points most inward.
            best_yaw, best_dot = axis, -2.0
            for k in range(4):
                yaw = axis + k * math.pi / 2
                dot = (math.sin(yaw) * vx + math.cos(yaw) * vz) / n
                if dot > best_dot:
                    best_dot, best_yaw = dot, yaw
            out.append(_Candidate(ix, iz, best_yaw, 1.0, None, "square in corner"))
        return out

    # WALL_BACK / WALL_FACE: slide along every bounding wall.
    for wall, line in hosts:
        L = line.length
        if L < w + 2 * gap:
            continue
        # Wall direction in scene space, and the inward normal.
        (ax, az), (bx, bz) = line.coords[0], line.coords[-1]
        dx, dz = (bx - ax) / L, (bz - az) / L
        for sign in (1.0, -1.0):
            nx, nz = -dz * sign, dx * sign
            probe = ShpPoint(
                (ax + bx) / 2 + nx * 0.35, (az + bz) / 2 + nz * 0.35
            )
            if not poly.contains(probe):
                continue  # that side of the wall is not this room
            # Yaw such that the item's local +z (its front) points inward.
            yaw = math.atan2(nx, nz)
            offset = d / 2.0 + wall.thickness_mm * MM_TO_M / 2.0 + gap
            steps = max(1, int((L - w) / (cfg.slide_step_mm * MM_TO_M)))
            for s in range(steps + 1):
                t = (w / 2.0) + s * (L - w) / steps if steps else L / 2.0
                px = ax + dx * t + nx * offset
                pz = az + dz * t + nz * offset
                # Prefer centred on the wall: bed and sofa symmetry reads as design.
                centred = 1.0 - abs(t - L / 2.0) / max(L / 2.0, 1e-6)
                out.append(
                    _Candidate(
                        px,
                        pz,
                        yaw,
                        0.55 + 0.45 * centred + min(L, 6.0) / 12.0,
                        wall.id,
                        f"against {wall.length_mm/1000:.1f} m wall",
                    )
                )
    return out


def _score_candidate(
    cand: _Candidate,
    item: FurnitureItem,
    poly: ShpPolygon,
    occupied: list[ShpPolygon],
    swings: Sequence[ShpPolygon],
    soft_swings: Sequence[ShpPolygon],
    windows: Sequence[ShpPoint],
    cfg: SolverConfig,
    open_area: ShpPolygon | None = None,
) -> float | None:
    """Return a score, or None if a hard constraint is violated."""
    w = item.width_mm * MM_TO_M
    d = item.depth_mm * MM_TO_M
    fp = _oriented_box(cand.x, cand.z, w, d, cand.yaw)

    # Hard: entirely inside the room. A small tolerance absorbs the polygon's own
    # discretisation without letting furniture poke through a wall.
    if not poly.buffer(0.02).contains(fp):
        return None
    # Hard: no overlap with what is already placed.
    for occ in occupied:
        if fp.intersection(occ).area > 1e-4:
            return None
    # Hard: does not block a door swing.
    for z in swings:
        if fp.intersection(z).area > 1e-4:
            return None

    # Hard: declared clearance must be free floor. Modelled as a band in front of
    # the item, in its own facing direction.
    if item.clearance_front_mm > 0:
        c = item.clearance_front_mm * MM_TO_M
        fx, fz = math.sin(cand.yaw), math.cos(cand.yaw)
        zone = _oriented_box(cand.x + fx * (d / 2 + c / 2), cand.z + fz * (d / 2 + c / 2), w, c, cand.yaw)
        # Clearance may extend into space this room is continuously open to; the item
        # itself may not.
        usable = open_area if open_area is not None else poly
        if not usable.buffer(0.02).contains(zone):
            return None
        for occ in occupied:
            if zone.intersection(occ).area > 0.02:
                return None

    score = cand.score

    # Soft: keep an inferred door's swing clear if we can, but do not refuse to
    # furnish the room over it.
    for z in soft_swings:
        overlap = fp.intersection(z).area
        if overlap > 0:
            score -= 2.5 * overlap / max(z.area, 1e-6)

    # Soft: seating and beds prefer a view of a window.
    if windows and ("seating" in item.tags or "sleeping" in item.tags):
        nearest = min(math.dist((cand.x, cand.z), (p.x, p.y)) for p in windows)
        score += max(0.0, 1.6 - nearest * 0.18)

    # Soft: keep the room's centre walkable. Penalise proportionally to how much
    # of the centre band the item eats, rather than forbidding it, so a small room
    # can still be furnished.
    centre_band = poly.centroid.buffer(cfg.circulation_width_mm * MM_TO_M)
    overlap = fp.intersection(centre_band).area
    if overlap > 0:
        score -= 2.2 * overlap / max(centre_band.area, 1e-6)

    return score


def furnish_room(
    plan: PlanIR,
    room: Room,
    *,
    origin: tuple[float, float],
    cfg: SolverConfig | None = None,
    locked: Sequence[FurniturePlacement] = (),
    wanted: Sequence[str] | None = None,
    open_area: ShpPolygon | None = None,
) -> LayoutResult:
    """Lay out one room. ``wanted`` overrides the default item selection.

    ``open_area`` is the room plus any space it runs into with no wall between — the
    floor a person can actually use standing in it. Clearance is tested against that
    rather than against the room's own outline, because in an open plan the space in
    front of the sofa genuinely is the dining zone. Without it the living room rejected
    a sofa, both sofas, the coffee table and the rug: a 2.1 m sofa with 900 mm in front
    of it needs a 2.1 x 1.8 m block, and the living zone fills only 51% of its bounding
    box, so no such block fits inside the zone *alone*.
    """
    cfg = cfg or SolverConfig()
    result = LayoutResult()
    poly = _room_polygon_m(room, origin)
    if poly.area < 1.0 or not room.kind.is_habitable and room.kind not in (
        RoomKind.BATHROOM,
        RoomKind.POWDER,
        RoomKind.BALCONY,
        RoomKind.DRY_BALCONY,
        RoomKind.UTILITY,
        RoomKind.WARDROBE,
        RoomKind.TERRACE,
        RoomKind.LOBBY,
    ):
        return result

    # Guards *are* something to place furniture against, even though they are not room
    # dividers.
    #
    # Excluding them was over-strict. A chair or a planter against a balcony balustrade is
    # entirely normal, and with the guards hidden the balconies had almost no wall to anchor
    # to: 63 of 169 rejections across the drawing were balcony furniture — every outdoor
    # table, most outdoor chairs, most washing machines. They stay excluded everywhere they
    # would act as a partition; this is the one place where what matters is that they are a
    # vertical surface at the room's edge.
    walls = list(plan.walls)
    swings, soft_swings = _door_swing_zones(plan, room, origin, cfg)

    windows: list[ShpPoint] = []
    for o in plan.openings:
        if o.kind.is_door:
            continue
        wall = plan.wall_by_id(o.wall_id)
        if wall is None:
            continue
        p = _wall_line_m(wall, origin).interpolate(o.t_center, normalized=True)
        if poly.distance(p) < 0.6:
            windows.append(p)

    occupied: list[ShpPolygon] = []
    for lp in locked:
        occupied.append(
            _oriented_box(lp.position[0], lp.position[2], lp.footprint[0], lp.footprint[1], lp.rotation_y)
        )
    result.placements.extend(locked)

    area = poly.area
    groups: list[list[FurnitureItem]] = (
        [[CATALOG[i]] for i in wanted if i in CATALOG]
        if wanted is not None
        else _select_items(room.kind, area)
    )

    placed_by_cat: dict[str, int] = {}
    parents: dict[str, FurniturePlacement] = {}

    for alternatives in groups:
        if len(result.placements) >= cfg.max_items_per_room + len(locked):
            break
        # Try the preferred item, then progressively smaller ones in the same
        # category, until one fits the room's actual shape.
        item = alternatives[0]
        chosen: FurnitureItem | None = None
        best: tuple[float, _Candidate] | None = None
        scale = 1.0
        for alt in alternatives:
            # Full size first, then progressively smaller down to the item's declared
            # floor. Real furniture comes in sizes — a 1 m desk is still a desk — so a
            # compact room should get the smaller version rather than nothing at all. Nine
            # of seventeen failures on the demo flat were bedroom desks, chairs and bedside
            # tables rejected in rooms that would take a smaller one comfortably.
            #
            # Coarse steps on purpose: this is choosing between sizes a manufacturer would
            # actually make, not searching for the largest object that squeezes in.
            for factor in _shrink_steps(alt.min_scale):
                sized = _scaled(alt, factor)
                cands = (
                    _relative_candidates(sized, parents, poly, cfg)
                    if sized.anchor is Anchor.RELATIVE
                    else _anchor_candidates(sized, room, walls, origin, cfg)
                )
                trial: tuple[float, _Candidate] | None = None
                for c in cands:
                    sc = _score_candidate(
                        c, sized, poly, occupied, swings, soft_swings, windows, cfg, open_area
                    )
                    if sc is None:
                        continue
                    # A shrunk item is a compromise, so a full-size fit always wins when
                    # both are possible. Ordering the steps largest-first already ensures
                    # that; the penalty keeps it true if scoring is ever reordered.
                    sc -= (1.0 - factor) * 4.0
                    if trial is None or sc > trial[0]:
                        trial = (sc, c)
                if trial is not None:
                    chosen, best, item, scale = sized, trial, sized, factor
                    break
            if chosen is not None:
                break
            result.rejected.setdefault(
                alt.id,
                f"no position satisfied clearance, door swing and collision constraints"
                + (f" even at {int(alt.min_scale * 100)}% size" if alt.min_scale < 1.0 else ""),
            )
        if chosen is None or best is None:
            continue

        n_placed = placed_by_cat.get(item.category, 0)
        for _ in range(max(1, item.max_count - n_placed)):
            if best is None:
                cands = (
                    _relative_candidates(item, parents, poly, cfg)
                    if item.anchor is Anchor.RELATIVE
                    else _anchor_candidates(item, room, walls, origin, cfg)
                )
                for c in cands:
                    sc = _score_candidate(c, item, poly, occupied, swings, soft_swings, windows, cfg, open_area)
                    if sc is None:
                        continue
                    if best is None or sc > best[0]:
                        best = (sc, c)
            if best is None:
                break

            score, c = best
            best = None
            w = item.width_mm * MM_TO_M
            d = item.depth_mm * MM_TO_M
            pl = FurniturePlacement(
                id=f"{room.id}-{item.id}-{placed_by_cat.get(item.category, 0) + 1}",
                catalog_id=item.id,
                room_id=room.id,
                position=(c.x, room.floor_level_mm * MM_TO_M, c.z),
                rotation_y=c.yaw,
                # Plan dimensions scale, height does not — a shorter desk is not a desk.
                # Both renderers read this, so a shrunk item is drawn shrunk without either
                # of them needing to know why.
                scale=(scale, 1.0, scale),
                footprint=(w, d),
                height=item.height_mm * MM_TO_M,
                clearance=(
                    item.clearance_front_mm * MM_TO_M,
                    item.clearance_back_mm * MM_TO_M,
                    item.clearance_sides_mm * MM_TO_M,
                    item.clearance_sides_mm * MM_TO_M,
                ),
                anchored_to_wall=c.wall_id,
                source="solver",
                reason=f"{c.reason} (score {score:.2f})",
            )
            result.placements.append(pl)
            result.rejected.pop(item.id, None)
            occupied.append(_oriented_box(c.x, c.z, w, d, c.yaw))
            placed_by_cat[item.category] = placed_by_cat.get(item.category, 0) + 1
            parents.setdefault(item.category, pl)

    return result


def _open_floor_candidates(poly: ShpPolygon, cfg: SolverConfig) -> list[_Candidate]:
    """Positions over a room's open floor, most central first.

    "Centred in the room" has to mean the most central place the item actually fits, not
    literally the centroid. Offering only the centroid, at two rotations, gave a dining
    table exactly two chances — and the centroid of a ragged zone is often a spot where a
    1.8 x 1.94 m table pokes out through the outline. The centroid of an L-shaped room can
    even lie outside the room.

    Candidates start from the pole of inaccessibility — the centre of the largest circle
    that fits inside the polygon — and fan out over a coarse grid, scored by how central
    they are. Containment and clearance still decide what is allowed.
    """
    try:
        from shapely.algorithms.polylabel import polylabel

        pole = polylabel(poly, tolerance=0.1)
    except Exception:
        pole = poly.representative_point()

    step = max(0.25, cfg.slide_step_mm * MM_TO_M * 3)
    minx, minz, maxx, maxz = poly.bounds
    span = max(maxx - minx, maxz - minz) or 1.0
    out: list[_Candidate] = []
    for yaw in (0.0, math.pi / 2):
        out.append(_Candidate(pole.x, pole.y, yaw, 1.2, None, "most open point in room"))
    seen: set[tuple[int, int]] = set()
    z = minz + step / 2
    while z < maxz:
        x = minx + step / 2
        while x < maxx:
            key = (int(x / step), int(z / step))
            if key not in seen and poly.contains(ShpPoint(x, z)):
                seen.add(key)
                closeness = 1.0 - min(1.0, math.dist((x, z), (pole.x, pole.y)) / span)
                for yaw in (0.0, math.pi / 2):
                    out.append(
                        _Candidate(x, z, yaw, 0.4 + 0.6 * closeness, None, "placed in the open floor")
                    )
            x += step
        z += step
    return out


def _relative_candidates(
    item: FurnitureItem,
    parents: dict[str, FurniturePlacement],
    poly: ShpPolygon,
    cfg: SolverConfig,
) -> list[_Candidate]:
    """Positions for an item that relates to another: bedside beside the bed, etc.

    Placed by reference to the parent's own frame, so a rotated bed takes its
    bedside tables with it. Without this, "relative" items end up in plausible
    absolute positions that are wrong relative to what they belong to.
    """
    rel = {
        "side_table": ("bed", "beside"),
        "coffee_table": ("sofa", "front"),
        "rug": ("sofa", "front"),
        "chair": ("desk", "front"),
        "outdoor_table": ("outdoor_chair", "beside"),
    }
    spec = rel.get(item.category)
    if spec is None:
        return [_Candidate(poly.centroid.x, poly.centroid.y, 0.0, 0.5, None, "room centre")]
    parent_cat, mode = spec
    parent = parents.get(parent_cat)
    if parent is None:
        # No parent placed, so place it on its own merits rather than not at all.
        #
        # Returning nothing here was the largest single source of rejections after the door
        # fixes: a rug relates to a sofa, so a living room with no sofa got no rug; a
        # balcony table relates to a chair that is placed *after* it, so it never had a
        # parent to relate to. A rug in the middle of the floor is still a rug.
        return _open_floor_candidates(poly, cfg)

    px, _, pz = parent.position
    yaw = parent.rotation_y
    fx, fz = math.sin(yaw), math.cos(yaw)          # parent's forward
    rx, rz = math.cos(yaw), -math.sin(yaw)         # parent's right
    pw, pd = parent.footprint
    out: list[_Candidate] = []

    if mode == "beside":
        off = pw / 2.0 + item.width_mm * MM_TO_M / 2.0 + 0.06
        for sgn in (1.0, -1.0):
            out.append(
                _Candidate(
                    px + rx * off * sgn - fx * (pd / 2 - item.depth_mm * MM_TO_M / 2),
                    pz + rz * off * sgn - fz * (pd / 2 - item.depth_mm * MM_TO_M / 2),
                    yaw,
                    1.0,
                    None,
                    f"beside {parent_cat}",
                )
            )
    else:  # in front of the parent
        for dist in (0.45, 0.6, 0.8):
            gap = pd / 2.0 + item.depth_mm * MM_TO_M / 2.0 + dist
            out.append(
                _Candidate(
                    px + fx * gap, pz + fz * gap, yaw, 1.0, None, f"in front of {parent_cat}"
                )
            )
    return out


def _select_items(kind: RoomKind, area_m2: float) -> list[list[FurnitureItem]]:
    """Choose what belongs in a room, as *alternatives per category*.

    Returns one list per category, largest/most-preferred first, and the caller places
    the first alternative that actually fits. Exactly one item per category ends up in
    the room — three beds in a bedroom is worse than one — but which one is decided by
    the geometry rather than by area alone.

    That distinction matters. Filtering by ``min_room_area_m2`` only asks "is the room
    big enough?", and a room can have ample area in a shape that defeats the item: the
    demo flat's living zone is 12.3 m² but shaped as a ribbon with 44 vertices, and a
    2.1 m three-seat sofa with its 900 mm clearance has nowhere to go in it. Offering
    the 1.6 m two-seater as a fallback furnishes the room instead of leaving it empty.
    """
    pool = items_for_room(kind, area_m2)
    groups: dict[str, list[FurnitureItem]] = {}
    for item in pool:
        # Dining tables belong in a dining room; in a living room only if it is large
        # enough to be a genuine living-dining.
        if item.category == "dining_table" and kind is RoomKind.LIVING and area_m2 < 22.0:
            continue
        groups.setdefault(item.category, []).append(item)

    ordered = list(groups.values())
    for alts in ordered:
        # Preferred first, then descending footprint, so fallbacks get smaller.
        alts.sort(key=lambda i: (-i.priority, -(i.width_mm * i.depth_mm)))
    ordered.sort(key=lambda alts: -alts[0].priority)
    return ordered


def furnish_plan(
    plan: PlanIR,
    *,
    origin: tuple[float, float],
    cfg: SolverConfig | None = None,
) -> LayoutResult:
    """Furnish every room, honouring fixtures already drawn in the CAD file."""
    cfg = cfg or SolverConfig()
    total = LayoutResult()

    # Which rooms run into one another with no wall between them? Walls now sit exactly
    # on space boundaries, so two rooms separated by one are a wall-thickness apart while
    # two sharing an open threshold touch at zero. That distinction is the whole signal.
    shapes = {r.id: _room_polygon_m(r, origin) for r in plan.rooms if len(r.polygon) >= 3}
    groups: dict[str, ShpPolygon] = {}
    ids = list(shapes)
    parent = {i: i for i in ids}

    def find(a: str) -> str:
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    for n, a in enumerate(ids):
        for b in ids[n + 1 :]:
            if shapes[a].distance(shapes[b]) <= 0.03:
                parent[find(a)] = find(b)
    for i in ids:
        root = find(i)
        groups[root] = groups[root].union(shapes[i]) if root in groups else shapes[i]

    for room in plan.rooms:
        locked = _locked_from_fixtures(plan, room, origin) if cfg.respect_locked else []
        open_area = groups.get(find(room.id)) if room.id in shapes else None
        res = furnish_room(
            plan, room, origin=origin, cfg=cfg, locked=locked, open_area=open_area
        )
        total.placements.extend(res.placements)
        for k, v in res.rejected.items():
            total.rejected.setdefault(f"{room.id}/{k}", v)

    placed = len(total.placements)
    locked_n = sum(1 for p in total.placements if p.locked)
    total.notes.append(
        f"placed {placed} items across {len(plan.rooms)} rooms "
        f"({locked_n} locked from the drawing, {len(total.rejected)} items could not be fitted)"
    )
    return total


_FIXTURE_TO_CATALOG = {
    "wc": "wc-wall-hung",
    "basin": "basin-vanity",
    "shower": "shower-enclosure",
    "counter": "counter-run",
    "kitchen_sink": "counter-run",
    "hob": "counter-run",
    "washing_machine": "washing-machine",
    "fridge": "fridge",
}


def _locked_from_fixtures(
    plan: PlanIR, room: Room, origin: tuple[float, float]
) -> list[FurniturePlacement]:
    """Convert drawn CAD fixtures into locked placements.

    These are the architect's decisions about plumbing and services. Re-deriving
    them from a layout heuristic would move a WC away from its soil stack, which is
    not a stylistic difference — it is unbuildable. So they are placed exactly where
    the drawing puts them and marked ``locked``.
    """
    ox, oy = origin
    out: list[FurniturePlacement] = []
    for fx in plan.fixtures:
        if fx.room_id != room.id or len(fx.footprint) < 3:
            continue
        cid = _FIXTURE_TO_CATALOG.get(fx.category)
        if cid is None or cid not in CATALOG:
            continue
        item = CATALOG[cid]
        xs = [p[0] for p in fx.footprint]
        ys = [p[1] for p in fx.footprint]
        cxm = ((min(xs) + max(xs)) / 2.0 - ox) * MM_TO_M
        czm = -((min(ys) + max(ys)) / 2.0 - oy) * MM_TO_M
        # Face the room centre: the drawn footprint gives position reliably but
        # not orientation, and a fixture facing a wall is obviously wrong.
        poly = _room_polygon_m(room, origin)
        yaw = math.atan2(poly.centroid.x - cxm, poly.centroid.y - czm)
        out.append(
            FurniturePlacement(
                id=f"{room.id}-{fx.id}-locked",
                catalog_id=cid,
                room_id=room.id,
                position=(cxm, room.floor_level_mm * MM_TO_M, czm),
                rotation_y=yaw,
                footprint=(item.width_mm * MM_TO_M, item.depth_mm * MM_TO_M),
                height=item.height_mm * MM_TO_M,
                locked=True,
                source="drawing",
                reason=f"read from CAD layer {fx.label!r}; position fixed by services",
            )
        )
    return out
